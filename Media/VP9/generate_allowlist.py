#!/usr/bin/env python3
"""Compile CoreMedia's existing policy plus one exact VP9 plugin cdhash.

The factored policy has the same Apple clauses as the original. Boolean
identities keep its encoded size at 200 bytes, so neither nearby data nor
CoreMedia's code needs changing. No signature check is disabled.
"""
from pathlib import Path
import re
import subprocess
import sys
import tempfile


ORIGINAL = (
    'anchor apple or anchor apple generic and '
    'info[CFBundleIdentifier] = "com.apple."* and '
    'certificate leaf[field.1.2.840.113635.100.6.1.9] or '
    'anchor apple generic and info[CFBundleIdentifier] = "com.apple."* and '
    'certificate leaf[field.1.2.840.113635.100.6.1.27]'
)
FACTORED = (
    'anchor apple or (anchor apple generic and '
    'info[CFBundleIdentifier] = "com.apple."* and '
    '(certificate leaf[field.1.2.840.113635.100.6.1.9] or '
    'certificate leaf[field.1.2.840.113635.100.6.1.27]))'
)


def run(*args):
    return subprocess.run(args, check=True, capture_output=True, text=True)


def compile_requirement(text, path):
    run("/usr/bin/csreq", "-r", "=" + text, "-b", str(path))
    data = path.read_bytes()
    if len(data) != 200:
        raise RuntimeError("Unexpected compiled requirement size: " + str(len(data)))
    return data


def generate(bundle, output):
    run("/usr/bin/codesign", "--verify", "--strict", str(bundle))
    signing = run("/usr/bin/codesign", "-d", "-vvv", str(bundle)).stderr
    match = re.search(r"^CDHash=([0-9a-f]{40})$", signing, re.MULTILINE)
    if not match:
        raise RuntimeError("Cannot identify plugin cdhash")
    cdhash = match[1]
    requirement = (
        f'({FACTORED} or cdhash H"{cdhash}") '
        'and always and always and !never'
    )
    run("/usr/bin/codesign", "--verify", "--strict", "-R", "=" + requirement,
        str(bundle))
    with tempfile.TemporaryDirectory(prefix="nred-vp9-policy-") as directory:
        temporary = Path(directory)
        original = compile_requirement(ORIGINAL, temporary / "original")
        replacement = compile_requirement(requirement, temporary / "replacement")

    lines = [
        "// Generated by Media/VP9/generate_allowlist.py; do not edit the bytes.",
        "// CoreMedia UUID 5B257039-4FC4-37F2-8E81-B310002CC57A (25G332).",
        "// Preserves every original Apple clause and adds only this plugin cdhash.",
        "#pragma once",
        "namespace VP9PluginAllowlist {",
        f'    static constexpr const char* CDHash = "{cdhash}";',
        "    static constexpr unsigned char CDHashBytes[] = {" +
        ", ".join(f"0x{byte:02X}" for byte in bytes.fromhex(cdhash)) + "};",
        "    static constexpr unsigned long long PageOffset = 0x0F923000ULL;",
        "    static constexpr unsigned long Offset = 0x110;",
    ]
    for name, data in (("Original", original), ("Replacement", replacement)):
        lines.append(f"    static constexpr unsigned char {name}[] = {{")
        for start in range(0, len(data), 16):
            lines.append("        " + ", ".join(
                f"0x{byte:02X}" for byte in data[start:start + 16]) + ",")
        lines.append("    };")
    lines += [
        '    static_assert(sizeof(Original) == sizeof(Replacement), "Policy size changed");',
        '    static_assert(Offset + sizeof(Original) <= 4096, "Policy crosses a page");',
        "}",
        "",
    ]
    output.write_text("\n".join(lines))
    print("VP9 plugin cdhash:", cdhash)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("usage: generate_allowlist.py PLUGIN_BUNDLE OUTPUT_HEADER")
    generate(Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve())
